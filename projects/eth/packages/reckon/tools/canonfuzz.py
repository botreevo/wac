#!/usr/bin/env python3
"""Random float-heavy wac programs, for tools/canonfuzz.sh: one per seed, deterministic.

    python3 tools/canonfuzz.py SEED > prog.wac

Each program starts from values that make NaNs of every kind (0/0, inf-inf, sqrt of a negative, NaNs with payloads,
negative and signalling ones), then mixes them through what the canonicalizer's stack model reasons about: chains of
arithmetic, locals reassigned and reread, loops, branches, `?:` (select), arrays, struct fields, helper calls and
returns, neg/abs/copysign (which move bits), f32 round trips, and comparisons and float-to-int conversions (which hide a
payload). It prints every variable's bits, so any NaN the program can see is in its output.
"""
import random
import sys

seed = int(sys.argv[1])
rnd = random.Random(seed)

BIN = ["+", "-", "*", "/"]
METH2 = ["min", "max", "copySign"]
METH1 = ["sqrt", "abs", "floor", "ceil", "trunc"]

vars_ = ["zero", "one", "nan", "inf", "pay", "npay", "sig", "neg", "tiny"]


def expr(depth, pool, calls=True):
    if depth <= 0 or rnd.random() < 0.25:
        return rnd.choice(pool)
    k = rnd.random()
    if not calls and 0.8 <= k < 0.86:
        k = 0.1                                                  # a helper's own body calls no helper: no recursion
    a = expr(depth - 1, pool, calls)
    if k < 0.35:
        return f"({a} {rnd.choice(BIN)} {expr(depth - 1, pool, calls)})"
    if k < 0.5:
        return f"{a}.{rnd.choice(METH2)}({expr(depth - 1, pool, calls)})"
    if k < 0.65:
        return f"{a}.{rnd.choice(METH1)}()"
    if k < 0.72:
        return f"(-{a})"
    if k < 0.8:
        return f"((({a}) as~ f32) as f64)"                       # demote, promote
    if k < 0.86:
        return f"h{rnd.randrange(2)}({a}, {expr(depth - 1, pool)})"
    if k < 0.93:
        return f"(({a}) < ({expr(depth - 1, pool, calls)}) ? {expr(depth - 1, pool, calls)} : {a})"
    return f"(((({a}) as~ f32) + (({expr(depth - 1, pool, calls)}) as~ f32)) as f64)"   # f32 arithmetic


out = []
w = out.append
w("// Generated by tools/canonfuzz.py, seed %d." % seed)
w('import { Sys } from "std";')
w("struct Box { f64 v; }")
w("string hex64(u64 b) {")
w('  string digits = "0123456789abcdef";')
w('  string out = "";')
w("  for (i32 i = 15; i >= 0; i--) {")
w("    i32 d = ((b >> ((i * 4) as@ u32 as u64)) & (15 as u64)) as~ i32;")
w("    out += digits.slice(d, d + 1);")
w("  }")
w("  return out;")
w("}")
for h in range(2):
    w(f"f64 h{h}(f64 x, f64 y) {{ f64 t = {expr(2, ['x', 'y'], False)}; return {expr(2, ['x', 'y', 't'], False)}; }}")
w("export i32 main(Sys sys) {")
w("  f64 zero = sys.args().len() as f64;")
w("  f64 one = zero + 1.0;")
w("  f64 nan = zero / zero;")
w("  f64 inf = one / zero;")
w(f"  f64 pay = f64.fromBits({hex(0x7FF8000000000001 + rnd.randrange(1 << 20))} as u64);")
w(f"  f64 npay = f64.fromBits({hex(0xFFF8000000000000 + rnd.randrange(1, 1 << 20))} as u64);")
w(f"  f64 sig = f64.fromBits({hex(0x7FF0000000000000 + rnd.randrange(1, 1 << 20))} as u64);")
w("  f64 neg = zero - 2.5;")
w("  f64 tiny = f64.fromBits(1 as u64);")
w("  f64[] arr = f64[].filled(4, 0.0);")
w("  i64 ints = 0 as i64;")
w("  i32 cmps = 0;")
pool = list(vars_)
boxes = []
n = 0
for _ in range(rnd.randrange(8, 20)):
    k = rnd.random()
    v = f"v{n}"
    if k < 0.4:
        w(f"  f64 {v} = {expr(3, pool)};")
        pool.append(v); n += 1
    elif k < 0.5 and n > 0:
        t = rnd.choice([p for p in pool if p.startswith("v")])
        w(f"  for (i32 i = 0; i < {rnd.randrange(1, 4)}; i++) {{ {t} = {expr(2, pool)}; }}")
    elif k < 0.6 and n > 0:
        t = rnd.choice([p for p in pool if p.startswith("v")])
        w(f"  if ({expr(1, pool)} < {expr(1, pool)}) {{ {t} = {expr(2, pool)}; }} else {{ {t} = {expr(2, pool)}; }}")
    elif k < 0.7:
        i = rnd.randrange(4)
        w(f"  arr[{i}] = {expr(2, pool)};")
        w(f"  f64 {v} = arr[{i}] + {expr(1, pool)};")
        pool.append(v); n += 1
    elif k < 0.76:
        w(f"  Box b{n} = Box({expr(2, pool)});")
        boxes.append(f"b{n}")
        w(f"  f64 {v} = b{n}.v;")
        pool.append(v); n += 1
    elif k < 0.83 and boxes:
        w(f"  {rnd.choice(boxes)}.v = {expr(2, pool)};")          # struct.set
    elif k < 0.88:
        # Seen only through a comparison: its payload must not matter, so eliding its check is allowed.
        w(f"  if ({expr(2, pool)} == {expr(2, pool)}) {{ cmps += 1; }}")
        w(f"  if (({expr(2, pool)}) != ({expr(1, pool)})) {{ cmps += 2; }}")
    else:
        # Converted to an integer only when it is not a NaN (a NaN would trap the conversion, the same everywhere).
        e = expr(2, pool)
        w(f"  {{ f64 c = {e}; if (c == c && c.abs() < 1.0e15) {{ ints = ints + (c as~ i64); }} }}")
for p in pool:
    w(f'  sys.log("{p} " + hex64(f64.toBits({p})));')
for i in range(4):
    w(f'  sys.log("arr{i} " + hex64(f64.toBits(arr[{i}])));')
for b in boxes:
    w(f'  sys.log("{b} " + hex64(f64.toBits({b}.v)));')        # a field read straight back: what struct.set stored
w('  sys.log("ints \\{ints} cmps \\{cmps}");')
w("  return 0;")
w("}")
print("\n".join(out))
