// The vectors in test/claims_vectors.wac: statement and recipe CIDs from @ipld/dag-cbor, EIP-712 digests and signatures
// from ethers (key 0x11…11; RFC 6979 on both sides, so wac's signatures must be byte-identical).
import { Wallet, TypedDataEncoder } from 'ethers'
import * as dagCbor from '@ipld/dag-cbor'
import { CID } from 'multiformats/cid'
import { sha256 } from 'multiformats/hashes/sha2'
import fs from 'node:fs'
const cidOf = async (v) => CID.create(1, dagCbor.code, await sha256.digest(dagCbor.encode(v)))
const A = CID.parse('bafkreihdwdcefgh4dqkjv67uzcmw7ojee6xedzdetojuzjevtenxquvyku')   // the empty raw block
const B = CID.parse('bafybeiczsscdsbs7ffqz55asqdf3smv6klcw3gofszvwlyarci47bgf354')   // the empty directory
const domain = { name: 'reckon', version: '2' }
const w = new Wallet('0x' + '11'.repeat(32))
const recipe = { machine: 'wasm-gc/det/1', format: 'unixfs-v1-2025+hidden', input: B }
const R = await cidOf(recipe)
const statements = [
  { v: { kind: 'derivation', recipe: R, output: A, runner: 'wac 7a0bf47 on V8' },
    t: { Derivation: [{ name: 'recipe', type: 'bytes' }, { name: 'output', type: 'bytes' }, { name: 'runner', type: 'string' }] },
    m: { recipe: R.bytes, output: A.bytes, runner: 'wac 7a0bf47 on V8' } },
  { v: { kind: 'endorsement', subject: B, scope: 'read all of it' },
    t: { Endorsement: [{ name: 'subject', type: 'bytes' }, { name: 'scope', type: 'string' }] }, m: { subject: B.bytes, scope: 'read all of it' } },
  { v: { kind: 'rejection', subject: A, reason: 'malware' },
    t: { Rejection: [{ name: 'subject', type: 'bytes' }, { name: 'reason', type: 'string' }] }, m: { subject: A.bytes, reason: 'malware' } },
]
const out = { recipe: R.toString(), address: w.address.toLowerCase(), domain: TypedDataEncoder.hashDomain(domain), statements: [] }
for (const s of statements) {
  out.statements.push({ id: (await cidOf(s.v)).toString(), digest: TypedDataEncoder.hash(domain, s.t, s.m), signature: await w.signTypedData(domain, s.t, s.m) })
}
const rev = { kind: 'revocation', statement: CID.parse(out.statements[0].id) }
const revT = { Revocation: [{ name: 'statement', type: 'bytes' }] }
out.statements.push({ id: (await cidOf(rev)).toString(), digest: TypedDataEncoder.hash(domain, revT, { statement: rev.statement.bytes }),
                      signature: await w.signTypedData(domain, revT, { statement: rev.statement.bytes }) })
// A signed envelope's block, as DAG-CBOR, for the first statement
const sig0 = Buffer.from(out.statements[0].signature.slice(2), 'hex')
out.envelope = (await cidOf({ statement: statements[0].v, signer: Buffer.from(w.address.slice(2), 'hex'), signature: sig0 })).toString()
fs.writeFileSync(new URL('../../test/claims_vectors.wac', import.meta.url),
  '// Generated by tools/oracle/claims.mjs from @ipld/dag-cbor and ethers. Do not edit.\n\nexport static string CLAIMS = ' + JSON.stringify(JSON.stringify(out)) + ';\n')
console.log(out)
