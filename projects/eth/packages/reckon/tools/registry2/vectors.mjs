// test/registry2_vectors.wac: the storage slots of contracts/Registry.sol, computed from solc's storage layout
// (contracts/Registry.layout.json, written by compile.cjs) with ethers and multiformats — not from the code under test.
//
//     node tools/registry2/vectors.mjs
import { keccak256, AbiCoder, toUtf8Bytes, concat, toBeHex, zeroPadValue } from '../oracle/node_modules/ethers/lib.esm/index.js';
import { CID } from '../oracle/node_modules/multiformats/dist/src/cid.js';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const layout = JSON.parse(fs.readFileSync(path.join(here, '../../contracts/Registry.layout.json'), 'utf8'));
const abi = AbiCoder.defaultAbiCoder();
const base = (label) => layout.storage.find((s) => s.label === label).slot;
const members = (label) => layout.structs['struct Registry.' + label];
// Solidity: m[k] lives at keccak256(abi.encode(k, slotOfM)); an address key is padded on the left, bytes32 as is.
const mapSlot = (keyType, key, slot) => keccak256(abi.encode([keyType, 'uint256'], [key, slot]));
const nested = (outer, innerKey, slot) => mapSlot('bytes32', innerKey, BigInt(mapSlot('address', outer, slot)));
const plus = (slot, k) => toBeHex(BigInt(slot) + BigInt(k), 32);
const cidKey = (text) => keccak256(CID.parse(text).bytes);

const addrs = ['0x19e7e376e7c213b7e7e7e46cc70a5dd086daff2a', '0x0000000000000000000000000000000000000001', '0xffffffffffffffffffffffffffffffffffffffff'];
const cids = ['bafkreihdwdcefgh4dqkjv67uzcmw7ojee6xedzdetojuzjevtenxquvyku',
              'bafybeiczsscdsbs7ffqz55asqdf3smv6klcw3gofszvwlyarci47bgf354',
              'bafyreiex4vkxnzmyphunhcujjjvyeuiniugvbrd6ra3efokkfdusnfx6yi'];
const names = ['hello', 'notes', '', 'ünïcødé/name with spaces'];

const out = {
  solc: layout.solc,
  slots: Object.fromEntries(layout.storage.map((s) => [s.label, s.slot])),
  rejection: Object.fromEntries(members('Rejection').map((m) => [m.label, m.slot])),
  name: Object.fromEntries(members('Name').map((m) => [m.label, m.slot])),
  cids: cids.map((c) => ({ text: c, bytes: '0x' + Buffer.from(CID.parse(c).bytes).toString('hex'), key: cidKey(c) })),
  revoked: [], rejected: [], names: [],
};
for (const a of addrs) for (const c of cids) {
  out.revoked.push({ signer: a, cid: c, slot: nested(a, cidKey(c), base('revokedAt')) });
  const b = nested(a, cidKey(c), base('rejections'));
  out.rejected.push({ list: a, cid: c, since: plus(b, members('Rejection').find((m) => m.label === 'since').slot),
                      reason: plus(b, members('Rejection').find((m) => m.label === 'reason').slot) });
}
for (const a of addrs) for (const n of names) {
  const b = nested(a, keccak256(toUtf8Bytes(n)), base('names'));
  out.names.push({ publisher: a, name: n, slots: Object.fromEntries(members('Name').map((m) => [m.label, plus(b, m.slot)])) });
}
const text = JSON.stringify(out);
fs.writeFileSync(path.join(here, '../../test/registry2_vectors.wac'),
  '// Generated by tools/registry2/vectors.mjs from solc\'s storage layout, ethers and multiformats. Do not edit.\n\n' +
  'export static string REGISTRY2 = ' + JSON.stringify(text) + ';\n');
console.log(`${out.revoked.length} revocation, ${out.rejected.length} rejection and ${out.names.length} name vectors`);
