#!/usr/bin/env python3
# Write src/assets.wac from assets/: each file as a string the program serves, so the node is one file with
# nothing to install beside it. Run it after changing anything in assets/.
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
out = ["// Generated by tools/gen-assets.py from assets/ — edit those files and run it again.", ""]
for name, const in [("style.css", "STYLE"), ("wallet.js", "WALLET_JS"), ("favicon.svg", "FAVICON")]:
    text = (root / "assets" / name).read_text()
    # wac's string escapes are JSON's, plus `\{` for interpolation: a literal backslash is the only hazard.
    lit = json.dumps(text, ensure_ascii=False)
    out.append(f"export static string {const} = {lit};")
(root / "src" / "assets.wac").write_text("\n".join(out) + "\n")
