"""Writes test/corpus/fuzz.sql: random expressions and queries over mixed-type data, for corpus.py to
record what the real SQLite answers. Deterministic: `python3 tools/fuzz.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 400
r = random.Random(seed)

def lit():
    k = r.randrange(11)
    if k == 0: return "NULL"
    if k == 1: return str(r.randint(-5, 5))
    if k == 2: return str(r.choice([0, 1, -1, 2, 7, 100, 9223372036854775807, -9223372036854775808, 4294967296]))
    if k == 3: return r.choice(["0.5", "-2.5", "1.0", "3.25", "1e3", "-0.0", "0.1", "1e18"])
    if k == 4: return "'" + r.choice(["", "a", "B", "abc", "Hello", "10", "2.5", " 7 ", "x'y", "é", "1e2", "-3"]).replace("'", "''") + "'"
    if k == 5: return r.choice(["X''", "X'00'", "X'616263'"])
    if k in (6, 7, 8): return r.choice(["a", "b", "c", "d"])
    return str(r.randint(0, 3))

FUNCS1 = ["abs", "length", "typeof", "upper", "lower", "hex", "quote", "unicode", "trim", "round", "sign"]
FUNCS2 = ["coalesce", "ifnull", "nullif", "instr", "max", "min", "round", "substr", "ltrim", "rtrim"]
BIN = ["+", "-", "*", "/", "%", "||", "=", "!=", "<", "<=", ">", ">=", "IS", "IS NOT", "AND", "OR", "&", "|", "<<", ">>"]

def expr(d=0):
    if d > 2 or r.random() < 0.3: return lit()
    k = r.randrange(12)
    if k < 4: return f"({expr(d+1)} {r.choice(BIN)} {expr(d+1)})"
    if k == 4: return f"{r.choice(FUNCS1)}({expr(d+1)})"
    if k == 5: return f"{r.choice(FUNCS2)}({expr(d+1)}, {expr(d+1)})"
    if k == 6: return f"substr({expr(d+1)}, {expr(d+1)}, {expr(d+1)})"
    if k == 7: return f"CAST({expr(d+1)} AS {r.choice(['INTEGER', 'REAL', 'TEXT', 'NUMERIC', 'BLOB'])})"
    if k == 8: return f"CASE {expr(d+1)} WHEN {expr(d+1)} THEN {expr(d+1)} ELSE {expr(d+1)} END"
    if k == 9: return f"({expr(d+1)} {'NOT ' if r.random() < .3 else ''}IN ({expr(d+1)}, {expr(d+1)}))"
    if k == 10: return f"({expr(d+1)} {'NOT ' if r.random() < .3 else ''}BETWEEN {expr(d+1)} AND {expr(d+1)})"
    return f"(- {expr(d+1)})" if r.random() < .5 else f"(NOT {expr(d+1)})"

out = ["-- Generated by tools/fuzz.py: random expressions over mixed-type columns.",
       "CREATE TABLE t (a, b INTEGER, c TEXT, d REAL);",
       "CREATE INDEX t_b ON t (b);"]
for i in range(30):
    vals = ", ".join(lit().replace("a", "'a'") if False else r.choice(["NULL", str(r.randint(-3, 3)), "'" + str(r.randint(-3, 3)) + "'", "'x" + str(i % 4) + "'", str(r.randint(-3, 3)) + ".5", "X'0" + str(i % 3) + "'"]) for _ in range(4))
    out.append(f"INSERT INTO t VALUES ({vals});")
for i in range(count):
    k = r.randrange(6)
    if k < 3:
        out.append(f"SELECT {expr()}, {expr()};")
    elif k == 3:
        out.append(f"SELECT rowid, {expr()} FROM t WHERE {expr()} ORDER BY rowid;")
    elif k == 4:
        col = r.choice("abcd")
        agg = r.choice(["count(*)", f"count({col})", f"sum(b)", f"total(d)", f"min({col})", f"max({col})", f"group_concat(c)", f"avg(b)"])
        out.append(f"SELECT {r.choice('abcd')} AS g, {agg} FROM t GROUP BY g ORDER BY g;")
    else:
        out.append(f"SELECT {r.choice('abcd')}, rowid FROM t WHERE {r.choice('abcd')} {r.choice(['=', '<', '>=', 'IS', '!='])} {lit()} ORDER BY 1, 2;")
open("test/corpus/fuzz.sql", "w").write("\n".join(out) + "\n")
