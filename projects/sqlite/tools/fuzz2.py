"""Writes test/corpus/fuzz2.sql: random schemas, changes and queries — constraints, conflicts, upserts,
joins, grouping, ordering, subqueries — for corpus.py to record what the real SQLite answers.
Deterministic: `python3 tools/fuzz2.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 300
r = random.Random(seed)

def val():
    k = r.randrange(8)
    if k == 0: return "NULL"
    if k < 4: return str(r.randint(-3, 9))
    # Reals here are never integral: which of 3 and 3.0 a UNION keeps depends on SQLite's scan order,
    # which is a planner choice rather than a meaning. tools/fuzz.py covers integral reals.
    if k == 4: return r.choice(["1.5", "-2.5", "3.75", "0.25"])
    if k == 5: return "'" + r.choice(["a", "b", "c", "A", "10", "x y", ""]) + "'"
    if k == 6: return "'" + str(r.randint(0, 9)) + "'"
    return r.choice(["X'01'", "X''"])

out = ["-- Generated by tools/fuzz2.py: schemas, changes and queries."]
out.append("CREATE TABLE p (id INTEGER PRIMARY KEY, k TEXT UNIQUE, n INTEGER NOT NULL DEFAULT 0, r REAL, v);")
out.append("CREATE TABLE q (pid INTEGER, tag TEXT, w NUMERIC, PRIMARY KEY (pid, tag));")
out.append("CREATE TABLE s (x, y, z TEXT COLLATE BINARY);")
out.append("CREATE INDEX q_w ON q (w);")
out.append("CREATE INDEX s_xy ON s (x, y DESC);")
cols = {"p": ["id", "k", "n", "r", "v"], "q": ["pid", "tag", "w"], "s": ["x", "y", "z"]}

def cond(t, alias=None):
    c = r.choice(cols[t])
    c = f"{alias}.{c}" if alias else c
    op = r.choice(["=", "<", ">", "<=", ">=", "!=", "IS", "IS NOT"])
    k = r.randrange(5)
    if k == 0: return f"{c} IS NULL"
    if k == 1: return f"{c} IN ({val()}, {val()})"
    if k == 2: return f"{c} BETWEEN {val()} AND {val()}"
    return f"{c} {op} {val()}"

def where(t, alias=None):
    n = r.randrange(3)
    if n == 0: return ""
    parts = [cond(t, alias) for _ in range(n)]
    return " WHERE " + f" {r.choice(['AND', 'OR'])} ".join(parts)

def stmt():
    k = r.randrange(16)
    if k < 4:
        t = r.choice(["p", "q", "s"])
        verb = r.choice(["INSERT", "INSERT OR IGNORE", "INSERT OR REPLACE", "REPLACE"])
        cs = r.sample(cols[t], r.randint(1, len(cols[t])))
        rows = ", ".join("(" + ", ".join(val() for _ in cs) + ")" for _ in range(r.randint(1, 3)))
        up = ""
        if t == "p" and verb == "INSERT" and r.random() < 0.4:
            up = r.choice([" ON CONFLICT DO NOTHING", " ON CONFLICT(k) DO UPDATE SET n = n + 1, v = excluded.v",
                           " ON CONFLICT(id) DO UPDATE SET k = excluded.k WHERE excluded.n > 0"])
        return f"{verb} INTO {t} ({', '.join(cs)}) VALUES {rows}{up};"
    if k == 4:
        t = r.choice(["p", "q", "s"])
        c = r.choice(cols[t])
        return f"UPDATE {r.choice(['', 'OR IGNORE ', 'OR REPLACE '])}{t} SET {c} = {r.choice([val(), c + ' + 1', 'NULL'])}{where(t)};"
    if k == 5:
        t = r.choice(["p", "q", "s"])
        return f"DELETE FROM {t}{where(t)};"
    if k == 6:
        t = r.choice(["p", "q", "s"])
        return f"SELECT * FROM {t} ORDER BY {', '.join(cols[t])};"
    if k == 7:
        return f"SELECT p.id, p.k, q.tag FROM p {r.choice(['JOIN', 'LEFT JOIN'])} q ON q.pid = p.id{where('p', 'p')} ORDER BY 1, 2, 3;"
    if k == 8:
        t = r.choice(["p", "q", "s"])
        g = r.choice(cols[t]); a = r.choice(cols[t])
        return f"SELECT {g}, count(*), sum({a}), min({a}), max({a}) FROM {t}{where(t)} GROUP BY {g}{' HAVING count(*) > 1' if r.random() < .3 else ''} ORDER BY 1;"
    if k == 9:
        t = r.choice(["p", "q", "s"])
        c1, c2 = r.choice(cols[t]), r.choice(cols[t])
        return f"SELECT {c1}, {c2} FROM {t}{where(t)} ORDER BY {c1} {r.choice(['ASC', 'DESC'])}, {c2} {r.choice(['ASC', 'DESC'])}, rowid LIMIT {r.randint(0, 5)} OFFSET {r.randint(0, 2)};"
    if k == 10:
        t = r.choice(["p", "q", "s"])
        return f"SELECT DISTINCT {r.choice(cols[t])} FROM {t} ORDER BY 1;"
    if k == 11:
        return f"SELECT id FROM p WHERE id IN (SELECT pid FROM q{where('q')}) ORDER BY 1;"
    if k == 12:
        return f"SELECT k, (SELECT count(*) FROM q WHERE q.pid = p.id) FROM p ORDER BY k, id;"
    if k == 13:
        t = r.choice(["p", "q", "s"])
        c = r.choice(cols[t])
        return f"SELECT {c} FROM {t} UNION SELECT {r.choice(cols['s'])} FROM s ORDER BY 1;"
    if k == 14:
        return f"SELECT x, y FROM s WHERE x {r.choice(['=', '>', '<', '>='])} {val()} ORDER BY x, y DESC;"
    return f"SELECT count(*), total(n), count(k), max(k) FROM p{where('p')};"

for i in range(count):
    out.append(stmt())
open("test/corpus/fuzz2.sql", "w").write("\n".join(out) + "\n")
