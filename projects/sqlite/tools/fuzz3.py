"""Writes test/corpus/fuzz3.sql: random queries over the features the first two fuzzers do not reach —
window functions and frames, CTEs (recursive ones too), RIGHT/FULL/NATURAL joins, row values, compound
selects, JSON functions and json_each — for corpus.py to record what the real SQLite answers.
Every query orders its rows by all its columns, so only the answers are compared, never an order that
SQLite leaves to its planner. Deterministic: `python3 tools/fuzz3.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 200
r = random.Random(seed)

def val():
    k = r.randrange(9)
    if k == 0: return "NULL"
    if k < 5: return str(r.randint(-2, 6))
    if k == 5: return r.choice(["1.5", "-0.5", "2.25"])
    if k == 6: return "'" + r.choice(["a", "b", "B", "", "x y", "3"]) + "'"
    return str(r.randint(0, 3))

out = ["-- Generated by tools/fuzz3.py: windows, CTEs, joins, row values, JSON."]
out.append("CREATE TABLE a (id INTEGER PRIMARY KEY, g INTEGER, v, t TEXT);")
out.append("CREATE TABLE b (id INTEGER PRIMARY KEY, aid INTEGER, w, t TEXT);")
out.append("CREATE TABLE j (id INTEGER PRIMARY KEY, doc TEXT);")
for _ in range(r.randint(4, 12)):
    out.append(f"INSERT INTO a (g, v, t) VALUES ({r.randint(0, 3)}, {val()}, {val()});")
for _ in range(r.randint(3, 10)):
    out.append(f"INSERT INTO b (aid, w, t) VALUES ({r.randint(0, 8)}, {val()}, {val()});")

def jdoc(depth=0):
    k = r.randrange(6 if depth < 2 else 3)
    if k == 0: return str(r.randint(-3, 9))
    if k == 1: return '"' + r.choice(["p", "q", "r s", ""]) + '"'
    if k == 2: return r.choice(["true", "false", "null", "1.5"])
    if k == 3: return "[" + ",".join(jdoc(depth + 1) for _ in range(r.randint(0, 3))) + "]"
    keys = r.sample(["a", "b", "c", "d"], r.randint(0, 3))
    return "{" + ",".join(f'"{k}":{jdoc(depth + 1)}' for k in keys) + "}"

for _ in range(r.randint(3, 8)):
    out.append("INSERT INTO j (doc) VALUES ('" + jdoc().replace("'", "''") + "');")

ACOLS = ["a.id", "a.g", "a.v", "a.t"]
BCOLS = ["b.id", "b.aid", "b.w", "b.t"]

def scalar(cols):
    k = r.randrange(6)
    c = r.choice(cols)
    if k == 0: return f"({c} + {r.randint(0, 3)})"
    if k == 1: return f"coalesce({c}, {val()})"
    if k == 2: return f"typeof({c})"
    if k == 3: return f"({c} * {r.choice(['2', '-1', '0.5'])})"
    return c

def frame(total):
    if r.randrange(3) == 0: return ""
    # ROWS counts rows, so it needs an order with no ties; RANGE and GROUPS go by peers, which any order has.
    unit = r.choice(["ROWS", "RANGE", "GROUPS"] if total else ["RANGE", "GROUPS"])
    lo = r.choice(["UNBOUNDED PRECEDING", "1 PRECEDING", "CURRENT ROW", "2 PRECEDING"])
    hi = r.choice(["CURRENT ROW", "1 FOLLOWING", "UNBOUNDED FOLLOWING"])
    if unit == "RANGE" and ("1 " in lo or "2 " in lo or "1 " in hi): unit = "GROUPS"
    if lo == "CURRENT ROW" and hi == "CURRENT ROW": hi = "UNBOUNDED FOLLOWING"
    ex = r.choice(["", "", " EXCLUDE CURRENT ROW", " EXCLUDE TIES", " EXCLUDE GROUP"])
    return f" {unit} BETWEEN {lo} AND {hi}{ex}"

# Functions whose answer depends on the order of rows within the partition, not just on peers: they get
# an order with no ties (ending in a.id), since SQLite leaves any other order to its planner.
ORDERED = {"row_number", "lag", "lead", "first_value", "last_value", "nth_value", "ntile", "group_concat"}

def window():
    fn = r.choice(["row_number()", "rank()", "dense_rank()", "count(*)", "sum(a.g)", "min(a.v)", "max(a.t)",
                   "lag(a.v)", "lead(a.g, 1, -1)", "first_value(a.v)", "last_value(a.g)", "ntile(2)",
                   "percent_rank()", "cume_dist()", "nth_value(a.g, 2)", "group_concat(a.id, '-')", "avg(a.g)"])
    name = fn.split("(")[0]
    part = r.choice(["", "PARTITION BY a.g ", "PARTITION BY a.t "])
    total = r.choice(["ORDER BY a.id", "ORDER BY a.g, a.id", "ORDER BY a.v DESC, a.id", "ORDER BY a.t, a.id"])
    order = total if name in ORDERED else r.choice(["", total, "ORDER BY a.g", "ORDER BY a.t DESC"])
    framed = order and name not in ("row_number", "rank", "dense_rank", "ntile", "percent_rank", "cume_dist", "lag", "lead")
    fr = frame(order.endswith("a.id")) if framed else ""
    return f"{fn} OVER ({part}{order}{fr})"

def ordered(cols_n):
    return " ORDER BY " + ", ".join(str(i + 1) for i in range(cols_n))

def q_window():
    ws = [window() for _ in range(r.randint(1, 3))]
    sel = ["a.id"] + ws
    return f"SELECT {', '.join(sel)} FROM a" + ordered(len(sel)) + ";"

def q_join():
    kind = r.choice(["JOIN", "LEFT JOIN", "RIGHT JOIN", "FULL JOIN", "CROSS JOIN"])
    on = "" if kind == "CROSS JOIN" else r.choice([" ON b.aid = a.id", " ON b.aid = a.g", " ON a.t = b.t", " USING (t)", " USING (id)"])
    sel = [scalar(ACOLS), scalar(BCOLS)]
    if "USING" in on and r.randrange(2): sel.append("t")
    w = r.choice(["", f" WHERE a.g IS NOT {val()}", f" WHERE b.w > {val()} OR a.v IS NULL"])
    return f"SELECT {', '.join(sel)} FROM a {kind} b{on}{w}" + ordered(len(sel)) + ";"

def q_natural():
    return "SELECT * FROM a NATURAL " + r.choice(["JOIN", "LEFT JOIN", "FULL JOIN"]) + " b ORDER BY 1, 2, 3, 4, 5, 6;"

def q_cte():
    k = r.randrange(3)
    if k == 0:
        n = r.randint(1, 8)
        return (f"WITH RECURSIVE c(x) AS (SELECT {r.randint(0, 3)} UNION ALL SELECT x + {r.randint(1, 2)} FROM c WHERE x < {n}) "
                f"SELECT x, (SELECT count(*) FROM a WHERE a.g <= c.x) FROM c ORDER BY 1, 2;")
    if k == 1:
        return (f"WITH s AS (SELECT g, count(*) AS n, sum(v) AS tot FROM a GROUP BY g) "
                f"SELECT s.g, s.n, s.tot, b.id FROM s LEFT JOIN b ON b.aid = s.g ORDER BY 1, 2, 3, 4;")
    return (f"WITH RECURSIVE t(n, acc) AS (SELECT 1, '' UNION ALL SELECT n + 1, acc || n FROM t WHERE n < {r.randint(2, 6)}) "
            f"SELECT n, acc FROM t ORDER BY 1, 2;")

def q_rowvalue():
    k = r.randrange(4)
    if k == 0: return f"SELECT id FROM a WHERE (g, v) {r.choice(['=', '<', '>=', '<>', 'IS'])} ({val()}, {val()}) ORDER BY 1;"
    if k == 1: return f"SELECT id FROM a WHERE (g, t) IN (SELECT aid, t FROM b) ORDER BY 1;"
    if k == 2: return f"SELECT id FROM a WHERE (g, v) NOT IN (({val()}, {val()}), ({val()}, {val()})) ORDER BY 1;"
    return f"SELECT id, (g, id) > ({r.randint(0, 3)}, {r.randint(0, 6)}) FROM a ORDER BY 1, 2;"

def q_compound():
    op = r.choice(["UNION", "UNION ALL", "INTERSECT", "EXCEPT"])
    return f"SELECT g, t FROM a WHERE id > {r.randint(0, 5)} {op} SELECT aid, t FROM b ORDER BY 1, 2;"

def q_group():
    agg = r.choice(["count(*)", "count(DISTINCT v)", "sum(v)", "total(v)", "avg(g)", "min(t)", "max(v)",
                    "group_concat(t, '|' ORDER BY id)", "json_group_array(v ORDER BY id)", "median(g)"])
    having = r.choice(["", f" HAVING count(*) > {r.randint(0, 2)}", f" HAVING {agg} IS NOT NULL"])
    return f"SELECT g, {agg} FROM a GROUP BY g{having} ORDER BY 1, 2;"

def q_json():
    path = r.choice(["$", "$.a", "$.b", "$[0]", "$[1]", "$.a[0]", "$.c.d", "$[#-1]"])
    k = r.randrange(7)
    if k == 0: return f"SELECT id, json_extract(doc, '{path}'), json_type(doc, '{path}') FROM j ORDER BY 1, 2, 3;"
    if k == 1: return f"SELECT id, doc -> '{path}', doc ->> '{path}' FROM j ORDER BY 1, 2, 3;"
    if k == 2: return f"SELECT j.id, e.key, e.value, e.type, e.fullkey FROM j, json_each(j.doc) e ORDER BY 1, 2, 3, 4, 5;"
    if k == 3: return f"SELECT j.id, t.fullkey, t.type, t.atom FROM j, json_tree(j.doc) t ORDER BY 1, 2, 3, 4;"
    if k == 4: return f"SELECT id, json_set(doc, '{path}', {val()}), json_remove(doc, '{path}') FROM j ORDER BY 1, 2, 3;"
    if k == 5: return f"SELECT id, json_array_length(doc), json_valid(doc), json(jsonb(doc)) FROM j ORDER BY 1, 2, 3, 4;"
    return f"SELECT id, json_patch(doc, '{jdoc()}') FROM j ORDER BY 1, 2;"

def q_change():
    k = r.randrange(4)
    if k == 0: return f"UPDATE a SET (g, t) = ({r.randint(0, 3)}, {val()}) WHERE id = {r.randint(1, 10)};"
    # One FROM row per target row: with several, which one SQLite uses is its planner's choice.
    if k == 1: return f"UPDATE a SET v = bb.w FROM (SELECT aid, max(w) AS w FROM b GROUP BY aid) AS bb WHERE bb.aid = a.id;"
    if k == 2: return f"INSERT INTO a (g, v, t) SELECT aid % 4, w, t FROM b WHERE id = {r.randint(1, 8)};"
    return f"DELETE FROM b WHERE (aid, t) = ({r.randint(0, 8)}, {val()});"

kinds = [q_window, q_window, q_window, q_join, q_join, q_natural, q_cte, q_rowvalue, q_compound, q_group,
         q_json, q_json, q_change]
for _ in range(count):
    out.append(r.choice(kinds)())

open("test/corpus/fuzz3.sql", "w").write("\n".join(out) + "\n")
