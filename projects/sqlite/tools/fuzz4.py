"""Writes test/corpus/fuzz4.sql: a random schema using the constraint and schema features — conflict
clauses, foreign keys with actions, CHECK, generated columns, STRICT, WITHOUT ROWID, partial and
expression indexes, triggers — then random changes in and out of transactions and savepoints, each
followed now and then by the tables' contents, for corpus.py to record what the real SQLite answers.
Deterministic: `python3 tools/fuzz4.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 200
r = random.Random(seed)

def pick(*xs): return r.choice(xs)
def conflict(): return pick("", "", " ON CONFLICT REPLACE", " ON CONFLICT IGNORE", " ON CONFLICT FAIL", " ON CONFLICT ABORT")
def action(): return pick("CASCADE", "SET NULL", "SET DEFAULT", "RESTRICT", "NO ACTION")
def text(): return "'" + pick("a", "b", "c", "A", "dd", "x y", "") + "'"
def small(): return str(r.randint(-3, 6))
def val(): return pick("NULL", small(), small(), text(), "1.5")

out = ["-- Generated by tools/fuzz4.py: constraints, foreign keys, triggers, savepoints."]
out.append("PRAGMA foreign_keys = " + pick("ON", "ON", "OFF") + ";")
gen = pick("STORED", "VIRTUAL")
out.append(f"CREATE TABLE p (id INTEGER PRIMARY KEY{conflict()}, k TEXT UNIQUE{conflict()}, "
           f"n INTEGER NOT NULL{conflict()} DEFAULT 0, g AS (n * 2) {gen}, CHECK (n >= -2));")
out.append(f"CREATE TABLE c (id INTEGER PRIMARY KEY, pid INTEGER DEFAULT 1 REFERENCES p (id) ON DELETE {action()} "
           f"ON UPDATE {action()}, tag TEXT, UNIQUE (pid, tag){conflict()});")
strict = pick("", ", STRICT")
wtype = "TEXT" if strict else ""
out.append(f"CREATE TABLE w (k {wtype or 'TEXT'} PRIMARY KEY{conflict()}, v {'INTEGER' if strict else ''}) WITHOUT ROWID{strict};")
out.append("CREATE TABLE log (seq INTEGER PRIMARY KEY, what TEXT);")
if r.randrange(2): out.append("CREATE " + pick("", "UNIQUE ") + "INDEX c_part ON c (tag) WHERE pid > 2;")
if r.randrange(2): out.append("CREATE " + pick("", "UNIQUE ") + "INDEX p_low ON p (lower(k));")
if r.randrange(2): out.append("CREATE INDEX w_v ON w (v);")
if r.randrange(2):
    out.append("CREATE TRIGGER p_ins AFTER INSERT ON p BEGIN INSERT INTO log (what) VALUES ('ins ' || new.id || ' ' || coalesce(new.k, '-')); END;")
if r.randrange(2):
    out.append("CREATE TRIGGER p_upd AFTER UPDATE OF n ON p WHEN new.n <> old.n BEGIN INSERT INTO log (what) VALUES ('n ' || old.n || '>' || new.n); END;")
if r.randrange(2):
    out.append("CREATE TRIGGER c_del BEFORE DELETE ON c BEGIN INSERT INTO log (what) VALUES ('del c' || old.id); END;")
if r.randrange(2):
    out.append("CREATE TRIGGER p_skip BEFORE INSERT ON p WHEN new.k = 'dd' BEGIN SELECT RAISE(IGNORE); END;")
if r.randrange(3) == 0:
    out.append("CREATE TRIGGER w_guard BEFORE UPDATE ON w WHEN new.v > 5 BEGIN SELECT RAISE(ABORT, 'too big'); END;")

orx = lambda: pick("", "", "OR IGNORE ", "OR REPLACE ", "OR FAIL ", "OR ABORT ", "OR ROLLBACK ")

def change():
    k = r.randrange(16)
    if k < 3:
        rows = ", ".join(f"({pick('NULL', str(r.randint(1, 8)))}, {pick(text(), 'NULL')}, {pick(small(), 'NULL')})" for _ in range(r.randint(1, 3)))
        return f"INSERT {orx()}INTO p (id, k, n) VALUES {rows};"
    if k < 5:
        rows = ", ".join(f"({pick('NULL', str(r.randint(1, 10)))}, {pick(str(r.randint(0, 8)), 'NULL')}, {text()})" for _ in range(r.randint(1, 3)))
        return f"INSERT {orx()}INTO c (id, pid, tag) VALUES {rows};"
    if k == 5:
        return f"INSERT {orx()}INTO w VALUES ({pick(text(), 'NULL', small())}, {val()});"
    if k == 6:
        return f"INSERT INTO p (id, k, n) VALUES ({r.randint(1, 8)}, {text()}, {small()}) ON CONFLICT (id) DO UPDATE SET n = excluded.n + 1, k = coalesce(excluded.k, k);"
    if k == 7:
        return f"UPDATE {orx()}p SET n = n + {r.randint(-2, 2)} WHERE id {pick('=', '<', '>')} {r.randint(1, 6)};"
    if k == 8:
        return f"UPDATE {orx()}p SET id = id + {r.randint(1, 3)} WHERE id = {r.randint(1, 6)};"
    if k == 9:
        return f"UPDATE {orx()}c SET pid = {pick(str(r.randint(0, 8)), 'NULL')} WHERE id = {r.randint(1, 8)};"
    if k == 10:
        return f"UPDATE {orx()}w SET v = {val()} WHERE k = {text()};"
    if k == 11:
        return f"DELETE FROM p WHERE id {pick('=', '<', '>=')} {r.randint(1, 6)};"
    if k == 12:
        return f"DELETE FROM c WHERE tag = {text()};"
    if k == 13:
        return f"UPDATE {orx()}p SET k = {pick(text(), 'NULL')} WHERE id = {r.randint(1, 8)};"
    if k == 14:
        return f"REPLACE INTO c (id, pid, tag) VALUES ({r.randint(1, 6)}, {r.randint(1, 6)}, {text()});"
    return f"DELETE FROM w WHERE v IS {val()};"

def show():
    return pick("SELECT * FROM p ORDER BY id;", "SELECT * FROM c ORDER BY id;", "SELECT * FROM w ORDER BY k;",
                "SELECT what FROM log ORDER BY seq;", "SELECT count(*), sum(n), total(g) FROM p;",
                "SELECT id FROM c WHERE tag = 'a' AND pid > 2 ORDER BY id;", "SELECT id FROM p WHERE lower(k) = 'a' ORDER BY id;",
                "PRAGMA foreign_key_check;")

savepoints = []
in_tx = False
for _ in range(count):
    k = r.randrange(12)
    if k == 0 and not in_tx:
        out.append("BEGIN;"); in_tx = True
    elif k == 1 and in_tx:
        out.append(pick("COMMIT;", "ROLLBACK;")); in_tx = False; savepoints = []
    elif k == 2:
        name = pick("s1", "s2", "s3")
        out.append(f"SAVEPOINT {name};"); savepoints.append(name)
        in_tx = True
    elif k == 3 and savepoints:
        name = r.choice(savepoints)
        if r.randrange(2):
            out.append(f"ROLLBACK TO {name};")
            savepoints = savepoints[:savepoints.index(name) + 1]
        else:
            out.append(f"RELEASE {name};")
            savepoints = savepoints[:savepoints.index(name)]
            if not savepoints and in_tx and r.randrange(2): pass
    elif k == 4 and r.randrange(4) == 0:
        out.append(f"ALTER TABLE c ADD COLUMN extra{len(out)} DEFAULT {small()};")
    elif k < 9:
        out.append(change())
    else:
        out.append(show())
if in_tx: out.append("COMMIT;")
out += ["SELECT * FROM p ORDER BY id;", "SELECT * FROM c ORDER BY id;", "SELECT * FROM w ORDER BY k;",
        "SELECT what FROM log ORDER BY seq;"]

open("test/corpus/fuzz4.sql", "w").write("\n".join(out) + "\n")
