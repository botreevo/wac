"""Writes test/corpus/fuzz6.sql: random query shapes — views over joins and aggregates, correlated
subqueries in every clause, EXISTS and IN with NULLs, DISTINCT with ORDER BY, NULLS FIRST/LAST and
collations in ordering, LIMIT and OFFSET expressions, compound selects with their own ORDER BY and
LIMIT, HAVING on aggregates not selected — for corpus.py to record what the real SQLite answers.
Rows are always fully ordered, so only answers are compared. Deterministic: `python3 tools/fuzz6.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 200
r = random.Random(seed)

def pick(*xs): return r.choice(xs)
def val():
    return pick("NULL", str(r.randint(-2, 5)), str(r.randint(0, 3)), "'" + pick("a", "B", "b", "A", "", "c ") + "'", "1.5")

out = ["-- Generated by tools/fuzz6.py: query shapes."]
out.append("CREATE TABLE t (id INTEGER PRIMARY KEY, x, y TEXT COLLATE NOCASE, z REAL);")
out.append("CREATE TABLE u (id INTEGER PRIMARY KEY, tid INTEGER, w, v TEXT);")
for _ in range(r.randint(5, 12)):
    out.append(f"INSERT INTO t (x, y, z) VALUES ({val()}, {val()}, {val()});")
for _ in range(r.randint(4, 12)):
    out.append(f"INSERT INTO u (tid, w, v) VALUES ({r.randint(0, 9)}, {val()}, {val()});")
out.append("CREATE VIEW tv AS SELECT t.id, t.x, t.y, count(u.id) AS n, sum(u.w) AS sw FROM t LEFT JOIN u ON u.tid = t.id GROUP BY t.id;")
out.append("CREATE VIEW uv AS SELECT tid, max(w) AS mw, min(v) AS mv FROM u GROUP BY tid HAVING count(*) > " + str(r.randint(0, 1)) + ";")
out.append("CREATE VIEW both AS SELECT x AS k FROM t UNION SELECT w FROM u;")

def col(): return pick("t.x", "t.y", "t.z", "t.id")
def cond():
    k = r.randrange(9)
    c = col()
    if k == 0: return f"{c} IN (SELECT w FROM u WHERE u.tid = t.id)"
    if k == 1: return f"{c} NOT IN (SELECT w FROM u)"
    if k == 2: return f"EXISTS (SELECT 1 FROM u WHERE u.tid = t.id AND u.w > {val()})"
    if k == 3: return f"{c} > (SELECT avg(w) FROM u WHERE u.tid <> t.id)"
    if k == 4: return f"{c} IS NOT {val()}"
    if k == 5: return f"{c} IN ({val()}, {val()}, NULL)"
    if k == 6: return f"{c} BETWEEN {val()} AND {val()}"
    if k == 7: return f"coalesce({c}, {val()}) = {val()}"
    return f"{c} {pick('=', '<', '>=', '<>')} {val()}"

def order_terms(exprs):
    # Every output column, in a random order and direction, so the order is total.
    idx = list(range(1, len(exprs) + 1))
    r.shuffle(idx)
    return ", ".join(f"{i}{pick('', ' DESC')}{pick('', '', ' NULLS FIRST', ' NULLS LAST')}" for i in idx)

def q_where():
    sel = [col(), col(), f"(SELECT count(*) FROM u WHERE u.tid = t.id)"]
    w = " AND ".join(cond() for _ in range(r.randint(1, 2)))
    return f"SELECT {', '.join(sel)} FROM t WHERE {w} ORDER BY {order_terms(sel)};"

def q_distinct():
    sel = [pick("y", "x", "z"), pick("x % 2", "y || ''", "typeof(z)")]
    return f"SELECT DISTINCT {', '.join(sel)} FROM t ORDER BY {order_terms(sel)};"

def q_collate():
    c = pick("y", "x", "v")
    t = "u" if c == "v" else "t"
    return f"SELECT {c}, id FROM {t} ORDER BY {c} COLLATE {pick('NOCASE', 'BINARY', 'RTRIM')} {pick('', 'DESC')}, id;"

def q_limit():
    lim = pick(str(r.randint(0, 5)), "(SELECT count(*) FROM u) / 2", "-1", "2 + 1")
    off = pick("", f" OFFSET {r.randint(0, 3)}", " OFFSET (SELECT min(id) FROM u)")
    return f"SELECT id, x FROM t ORDER BY id {pick('', 'DESC')} LIMIT {lim}{off};"

def q_view():
    v = pick("tv", "uv", "both")
    if v == "tv": return f"SELECT * FROM tv WHERE n {pick('>', '=', '<=')} {r.randint(0, 2)} ORDER BY id;"
    if v == "uv": return "SELECT * FROM uv ORDER BY tid, mw, mv;"
    return "SELECT k, typeof(k) FROM both ORDER BY 1, 2;"

def q_join_view():
    return f"SELECT tv.id, tv.n, uv.mw FROM tv {pick('JOIN', 'LEFT JOIN')} uv ON uv.tid = tv.id ORDER BY 1, 2, 3;"

def q_having():
    agg = pick("count(*)", "sum(w)", "max(v)", "count(DISTINCT w)", "avg(w)")
    return f"SELECT tid FROM u GROUP BY tid HAVING {agg} {pick('>', '<', '=', 'IS NOT')} {val()} ORDER BY tid;"

def q_scalar_order():
    return "SELECT id, x FROM t ORDER BY (SELECT count(*) FROM u WHERE u.tid = t.id) DESC, x NULLS LAST, id;"

def q_compound():
    a = f"SELECT x FROM t WHERE id > {r.randint(0, 4)}"
    b = f"SELECT w FROM u WHERE tid < {r.randint(2, 8)}"
    op = pick("UNION", "UNION ALL", "INTERSECT", "EXCEPT")
    lim = pick("", f" LIMIT {r.randint(1, 6)}", f" LIMIT {r.randint(1, 4)} OFFSET 1")
    return f"SELECT * FROM ({a} {op} {b} ORDER BY 1{lim}) ORDER BY 1;"

def q_correlated_select():
    return (f"SELECT t.id, (SELECT group_concat(v, ',') FROM (SELECT v FROM u WHERE u.tid = t.id ORDER BY v, id)), "
            f"(SELECT max(w) FROM u WHERE u.tid = t.id AND u.w IS NOT NULL) FROM t ORDER BY 1;")

def q_in_null():
    return f"SELECT id, x IN (SELECT w FROM u), x NOT IN (SELECT w FROM u WHERE w IS NOT NULL), x IN () FROM t ORDER BY id;"

def q_group_expr():
    # Terms whose equal values all look alike: which row's value a group shows is SQLite's choice.
    e = pick("CAST(x AS INTEGER) % 2", "lower(y)", "typeof(z)", "length(y)", "x IS NULL")
    return f"SELECT {e}, count(*), min(id), max(z) FROM t GROUP BY {e} ORDER BY 1, 2, 3, 4;"

def q_nested():
    return (f"SELECT a.id, b.cnt FROM t AS a JOIN (SELECT tid, count(*) AS cnt FROM u GROUP BY tid) AS b ON b.tid = a.id "
            f"WHERE b.cnt >= {r.randint(1, 2)} ORDER BY 1, 2;")

kinds = [q_where, q_where, q_distinct, q_collate, q_limit, q_view, q_join_view, q_having, q_scalar_order, q_compound,
         q_correlated_select, q_in_null, q_group_expr, q_nested]
for _ in range(count):
    out.append(r.choice(kinds)())
open("test/corpus/fuzz6.sql", "w").write("\n".join(out) + "\n")
