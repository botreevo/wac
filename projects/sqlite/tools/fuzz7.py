"""Writes test/corpus/fuzz7.sql: random ALTER TABLE renames and drops over a schema whose views,
triggers, indexes and foreign keys name the tables and columns being changed, each followed by the
whole of sqlite_schema, whose text SQLite rewrites, and by changes that run through what was renamed,
for corpus.py to record what the real SQLite answers. Deterministic: `python3 tools/fuzz7.py [seed] [count]`."""
import random, sys

seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
count = int(sys.argv[2]) if len(sys.argv) > 2 else 60
r = random.Random(seed)

def pick(*xs): return r.choice(xs)

tables = {"a": ["id", "x", "y", "note"], "b": ["id", "aid", "w"]}
out = ["-- Generated by tools/fuzz7.py: ALTER TABLE against dependent objects."]
out.append("PRAGMA foreign_keys = " + pick("ON", "OFF") + ";")
out.append('CREATE TABLE a (id INTEGER PRIMARY KEY, x INTEGER, y TEXT, "note" TEXT DEFAULT \'n\', CHECK (x >= 0));')
out.append("CREATE TABLE b (id INTEGER PRIMARY KEY, aid INTEGER REFERENCES a (id) ON DELETE CASCADE, w);")
out.append("CREATE INDEX a_xy ON a (x, y);")
out.append("CREATE INDEX b_w ON b (w) WHERE aid > 0;")
out.append("CREATE VIEW av AS SELECT a.id, a.x + 1 AS x1, b.w FROM a LEFT JOIN b ON b.aid = a.id;")
out.append("CREATE VIEW cnt AS SELECT count(*) AS n, max(x) AS mx FROM a WHERE y IS NOT NULL;")
out.append("CREATE TABLE log (what TEXT);")
out.append("CREATE TRIGGER a_ins AFTER INSERT ON a BEGIN INSERT INTO log VALUES ('a ' || new.id || ' ' || new.x || ' ' || coalesce(new.y, '')); END;")
out.append("CREATE TRIGGER b_upd AFTER UPDATE OF w ON b WHEN new.w <> old.w BEGIN INSERT INTO log SELECT 'b ' || new.id || ' ' || a.x FROM a WHERE a.id = new.aid; END;")
for i in range(r.randint(2, 5)):
    out.append(f"INSERT INTO a (x, y) VALUES ({r.randint(0, 9)}, '{pick('p', 'q', 'r')}');")
for i in range(r.randint(2, 5)):
    out.append(f"INSERT INTO b (aid, w) VALUES ({r.randint(1, 4)}, {r.randint(0, 9)});")

show = "SELECT type, name, tbl_name, sql FROM sqlite_schema ORDER BY name;"
names = {"a": "a", "b": "b"}          # current names of the two tables
renamed = 0
for _ in range(count):
    k = r.randrange(8)
    t = pick("a", "b")
    cur = names[t]
    if k == 0:
        renamed += 1
        new = f"{t}{renamed}"
        out.append(f"ALTER TABLE {cur} RENAME TO {new};")
        names[t] = new
        out.append(show)
    elif k in (1, 2):
        cols = tables[t]
        c = pick(*[c for c in cols if c != "id"])
        new = c + str(r.randint(1, 9))
        out.append(f'ALTER TABLE {cur} RENAME COLUMN {pick(c, chr(34) + c + chr(34))} TO {new};')
        cols[cols.index(c)] = new
        out.append(show)
    elif k == 3:
        cols = tables[t]
        c = pick(*[c for c in cols if c != "id"])
        out.append(f"ALTER TABLE {cur} DROP COLUMN {c};")
        out.append(show)
        # Whether it was dropped depends on what still names it; SQLite says which.
    elif k == 4:
        c = f"extra{len(out)}"
        out.append(f"ALTER TABLE {cur} ADD COLUMN {c} {pick('TEXT', 'INTEGER', '')} DEFAULT {r.randint(0, 5)};")
        tables[t].append(c)
    elif k == 5:
        a, b = names["a"], names["b"]
        out.append(f"INSERT INTO {a} DEFAULT VALUES;")
        out.append(f"UPDATE {b} SET {pick(*[c for c in tables['b'] if c != 'id'])} = {r.randint(0, 9)} WHERE id = {r.randint(1, 4)};")
    elif k == 6:
        out.append(pick("SELECT * FROM av ORDER BY 1, 2, 3;", "SELECT * FROM cnt;", "SELECT * FROM log ORDER BY rowid;"))
    else:
        out.append(f"SELECT * FROM {names[t]} ORDER BY id;")
out.append(show)
out.append("SELECT * FROM log ORDER BY rowid;")
open("test/corpus/fuzz7.sql", "w").write("\n".join(out) + "\n")
